// Writes `sdks/python/tests/canonical_golden.json` — what `packages/core`'s canonical encoder
// actually produces, recorded so `fortyone._canonical` can be compared against it rather than
// against what somebody believes it produces (EPIC-054 ruling 4).
//
//     node scripts/write-canonical-golden.mjs
//
// **Run this by hand and read the diff**, like `scripts/write-artifact-fixtures.mts`. A test that
// regenerates its own expected value asserts nothing, and this one exists precisely to fail when
// the two languages stop agreeing. A diff here means either core's encoding moved — which is a
// change to a frozen format and therefore an ADR — or the generator grew a case, which is fine and
// is what the `cases` count in the file is for.
//
// Each entry is `{ input, canonical }` where `input` is **JSON text**, not a value: the Python side
// parses that text with its own parser, so the comparison covers the whole path from bytes to bytes
// and not merely the formatter in the middle.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalJson } from "../packages/core/src/artifact/canonical.js";

const NUMBERS = [
  0, -0, 1, 1.0, -1, 1.5, 0.1, 0.7, -3, 100, 123.456,
  1e15, 1e16, 1e20, 1e21, 1e22, 1.2e21, 1e21 - 1,
  1e-5, 1e-6, 1e-7, 1.5e-7, -1e-7, 2.5e-10,
  5e-324, 4.9e-324, 1e-323, 1.7976931348623157e308,
  0.30000000000000004, 1 / 3, Math.PI, Math.E,
  9007199254740991, 9007199254740992, 2 ** 53, 2 ** 53 + 2,
  1234567890123456789, 123456789012345678901234567890,
  -0.000001, 0.000001, 0.0000001, 1e100, -1e100, 6.02e23, 1.602176634e-19,
];

// Random doubles, seeded so the file is stable between runs. Exponent kept inside the finite range;
// a non-finite one has no canonical form by design and is covered by a unit test instead.
let seed = 0x41707231;
const next = () => (seed = (seed * 1103515245 + 12345) >>> 0) / 0x100000000;
const RANDOM = [];
for (let i = 0; i < 240; i += 1) {
  const mantissa = next() * 2 - 1;
  const exponent = Math.floor(next() * 260) - 130;
  const value = mantissa * 10 ** exponent;
  if (Number.isFinite(value)) RANDOM.push(value);
}

const STRINGS = [
  "", "plain", 'a"b', "back\\slash", "new\nline", "tab\there", "\b\f\r",
  // Written as escapes, never as raw bytes: a literal NUL makes git call the file binary and
  // show no diff for it, which `pnpm binary-files` exists to stop. It caught this line.
  "\u0000\u0001\u001f", "\u007f", "caf\u00e9", "\u65e5\u672c\u8a9e", "\ud83d\ude80 emoji",
  "\u2028\u2029", "\ud800", "\udfff", "lone \ud800 in the middle", "\u00a0nbsp",
];

// Key order is the second divergence: `<` on a JavaScript string is UTF-16 code unit order, and an
// astral-plane key sorts as its leading surrogate. The set below proves it, because a code-point
// sort puts U+F900 before U+1F680 and a code-unit sort does not.
const KEY_ORDER = {
  "🚀": 1, "豈": 2, "é": 3, a: 4, Z: 5, "": 6, "\ud800": 7, aa: 8, A: 9,
};

const values = [
  null, true, false, {}, [], [1, 2, 3], [[]], [{}, { a: [] }],
  ...NUMBERS.map((n) => ({ n })),
  ...RANDOM.map((n) => ({ n })),
  ...STRINGS.map((s) => ({ s })),
  ...STRINGS.map((s) => ({ [s]: 1 })),
  KEY_ORDER,
  { b: 1, a: 2, c: { z: [1, { y: 2, x: 3 }], a: null } },
  { params: { temperature: 1.0, top_p: 0.95, max_tokens: 1024, stream: false, stop: null } },
  { deep: { deep: { deep: { deep: [1e21, -0, "\ud800"] } } } },
];

const entries = values.map((value) => ({
  input: JSON.stringify(value),
  canonical: canonicalJson(value),
}));

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "sdks", "python", "tests", "canonical_golden.json");
writeFileSync(
  out,
  `${JSON.stringify(
    {
      note: "Generated by `node scripts/write-canonical-golden.mjs`. Do not edit. EPIC-054 ruling 4.",
      cases: entries.length,
      entries,
    },
    null,
    2,
  )}\n`,
);
console.log(`wrote ${entries.length} cases to sdks/python/tests/canonical_golden.json`);
